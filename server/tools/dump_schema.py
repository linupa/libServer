"""Write the database layout (tables, columns, keys, row counts) to schema.md.

Only structure and the small settings/code tables are written, never member or book rows.
Run with the Windows venv:  .venv\\Scripts\\python tools\\dump_schema.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from db import connect, rows  # noqa: E402

# Small tables that hold settings and codes, not personal data
SHOW_ROWS = {"CODE", "CODE_SUB", "LENT_OPTION"}


def main():
    conn = connect()
    tables = [r["TABLE_NAME"] for r in rows(conn,
              "SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_TYPE='BASE TABLE' ORDER BY TABLE_NAME")]
    keys = {}
    for r in rows(conn, """SELECT k.TABLE_NAME, k.COLUMN_NAME FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE k
                           JOIN INFORMATION_SCHEMA.TABLE_CONSTRAINTS c ON c.CONSTRAINT_NAME = k.CONSTRAINT_NAME
                           WHERE c.CONSTRAINT_TYPE = 'PRIMARY KEY'"""):
        keys.setdefault(r["TABLE_NAME"], set()).add(r["COLUMN_NAME"])

    out = ["# CLIB database layout", "", f"{len(tables)} tables. Generated by tools/dump_schema.py.", ""]
    for t in tables:
        count = rows(conn, f"SELECT COUNT(*) AS n FROM [{t}]")[0]["n"]
        out += [f"## {t} ({count} rows)", "", "| column | type | null | key |", "|---|---|---|---|"]
        for c in rows(conn, """SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_NULLABLE
                               FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = ? ORDER BY ORDINAL_POSITION""", t):
            size = c["CHARACTER_MAXIMUM_LENGTH"]
            kind = c["DATA_TYPE"] + (f"({'max' if size == -1 else size})" if size else "")
            out.append(f"| {c['COLUMN_NAME']} | {kind} | {'yes' if c['IS_NULLABLE'] == 'YES' else ''} | "
                       f"{'PK' if c['COLUMN_NAME'] in keys.get(t, ()) else ''} |")
        if t in SHOW_ROWS and count:
            data = rows(conn, f"SELECT * FROM [{t}]")
            cols = list(data[0])
            out += ["", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
            out += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in data]
        out.append("")
    (Path(__file__).resolve().parent.parent / "schema.md").write_text("\n".join(out), encoding="utf-8")
    print(f"{len(tables)} tables -> schema.md")


if __name__ == "__main__":
    main()
