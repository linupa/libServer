"""Convert CLIB's author-mark tables (Code/*.csv) into web/js/authorTables.js.

Usage: python3 tools/extract_author_tables.py "<CLIB install dir>" [web/js/authorTables.js]

- ljc*.csv (이재철 1-8표): 19 consonant rows then 21 vowel rows, "jamo,digits"
- 동양서저자기호.csv, 장일세.csv, CutterSanborn.csv: sorted "name,number" rows; an author
  takes the number of the last row whose name sorts at or before it
"""
import json
import sys
from pathlib import Path

LOOKUP = {"dongyang": "동양서저자기호.csv", "jang": "장일세.csv", "cutter": "CutterSanborn.csv"}


def rows(path):
    text = path.read_bytes()
    for enc in ("utf-8-sig", "cp949"):
        try:
            text = text.decode(enc)
            break
        except UnicodeDecodeError:
            continue
    out = []
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        # A quoted name may contain commas: "Smith, J",123
        if line.startswith('"') and '"' in line[1:]:
            end = line.index('"', 1)
            out.append([line[1:end], line[end + 2:].strip()])
        else:
            name, _, code = line.replace(" ", "").partition(",")
            out.append([name, code])
    # The lookup files end with a stray ";" row that has no number
    return [r for r in out if r[1]]


def main():
    code = Path(sys.argv[1]) / "Code"
    out = Path(sys.argv[2] if len(sys.argv) > 2 else Path(__file__).parent.parent / "web/js/authorTables.js")
    tables = {"ljc": {p.stem: rows(p) for p in sorted(code.glob("ljc*.csv"))}}
    for name, file in LOOKUP.items():
        tables[name] = rows(code / file)
    body = json.dumps(tables, ensure_ascii=False, separators=(",", ":"))
    out.write_text("// Generated by tools/extract_author_tables.py from CLIB's Code/*.csv. Do not edit.\n"
                   f"window.CLIB_AUTHOR_TABLES = {body};\n", encoding="utf-8")
    print(f"{len(tables['ljc'])} 이재철 tables, " +
          ", ".join(f"{k} {len(tables[k])} rows" for k in LOOKUP) + f" -> {out} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
